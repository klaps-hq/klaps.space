/**
 * Long-tail landing pages: /kino-plenerowe (open-air cinema, per city) and
 * /klasyka-w-kinach (classics, per month). The pages, the sitemap and the
 * hub links all decide indexability through the helpers here, so the three
 * can never disagree.
 */

export const OPEN_AIR_PATH = "/kino-plenerowe";
export const CLASSIC_PATH = "/klasyka-w-kinach";

/**
 * Look-back window for "last season" on the open-air pages. A full year, so
 * in winter the pages still show the summer that just ended.
 */
export const OPEN_AIR_SEASON_DAYS = 365;

/** Mirrors the API's CLASSIC_MIN_AGE_YEARS, which does the filtering. */
export const CLASSIC_MIN_AGE_YEARS = 25;

/**
 * Open-air pages stay indexable out of season when the city had at least
 * this many open-air screenings in the last year: the page then lists the
 * venues and last season's films, which is real content, and the query
 * peaks right when the season starts, too late to get indexed from scratch.
 */
export const OPEN_AIR_MIN_SEASON_SCREENINGS = 10;

// === Intros ===

/**
 * AI-written intro for a landing page, generated by the scraper and stored
 * in the API under keys like "open-air:lodz" or "classic:2026-11". null when
 * none exists yet or the call fails; pages then use a fallback built from
 * the data they already have.
 */
export const getLandingIntro = async (key: string): Promise<string | null> => {
  try {
    const intro = await apiFetch<{ content: string }>(
      `/landing-intros/${encodeURIComponent(key)}`
    );
    return intro.content?.trim() || null;
  } catch {
    return null;
  }
};

export const landingIntroKeys = {
  openAir: "open-air",
  openAirCity: (citySlug: string) => `open-air:${citySlug}`,
  classic: "classic",
  classicMonth: (yearMonth: string) => `classic:${yearMonth}`,
};

// === Open-air ===

export interface OpenAirCity {
  city: ICity;
  cinemas: ICinemaSummary[];
}

/** Open-air venues, throws on failure (the page 404s or 500s on it). */
export const fetchOpenAirCinemas = (): Promise<ICinemaSummary[]> =>
  apiFetch<ICinemaSummary[]>("/cinemas", { params: { openAir: "true" } });

/** Cities with open-air venues, the ones with the most venues first. */
export const groupOpenAirCities = (
  cinemas: ICinemaSummary[]
): OpenAirCity[] => {
  const byCity = new Map<string, OpenAirCity>();
  for (const cinema of cinemas) {
    const entry = byCity.get(cinema.city.slug) ?? {
      city: cinema.city,
      cinemas: [],
    };
    entry.cinemas.push(cinema);
    byCity.set(cinema.city.slug, entry);
  }
  return [...byCity.values()]
    .map((entry) => ({
      ...entry,
      cinemas: [...entry.cinemas].sort((a, b) =>
        a.name.localeCompare(b.name, "pl")
      ),
    }))
    .sort(
      (a, b) =>
        b.cinemas.length - a.cinemas.length ||
        a.city.name.localeCompare(b.city.name, "pl")
    );
};

export const getOpenAirCities = async (): Promise<OpenAirCity[]> =>
  groupOpenAirCities(await fetchOpenAirCinemas());

/** Upcoming open-air screenings, nationwide or in one city. */
export const fetchOpenAirScreenings = (citySlug?: string) =>
  fetchScreenings({ openAir: true, citySlug: citySlug ?? null });

/** Films shown at open-air venues over the last year, newest first. */
export const fetchOpenAirSeason = (cityId?: number) =>
  fetchRecentScreenings({
    openAir: true,
    cityId: cityId ? String(cityId) : null,
    days: OPEN_AIR_SEASON_DAYS,
    limit: 48,
  });

export const countScreenings = (groups: IScreeningGroup[]): number =>
  groups.reduce((sum, group) => sum + group.screenings.length, 0);

export const countSeasonScreenings = (items: IRecentScreening[]): number =>
  items.reduce((sum, item) => sum + item.screeningsCount, 0);

/**
 * Index decision for an open-air page. null means a call failed and the
 * answer is unknown: the page then leaves robots alone rather than noindex
 * itself for the whole ISR window on a backend hiccup.
 */
export const isOpenAirIndexable = (
  upcoming: IScreeningGroup[] | null,
  season: IRecentScreening[] | null
): boolean | null => {
  if (upcoming && upcoming.length > 0) return true;
  if (season && countSeasonScreenings(season) >= OPEN_AIR_MIN_SEASON_SCREENINGS)
    return true;
  if (upcoming === null || season === null) return null;
  return false;
};

/** Open-air data for one city page (or the hub when `city` is undefined). */
export const getOpenAirPageData = async (city?: ICity) => {
  const [upcoming, season] = await Promise.all([
    fetchOpenAirScreenings(city?.slug).catch(() => null),
    fetchOpenAirSeason(city?.id).catch(() => null),
  ]);
  return {
    upcoming,
    season,
    indexable: isOpenAirIndexable(upcoming, season),
  };
};

// === Classics per month ===

// Nominative, locative ("w listopadzie") and the ASCII form used in URLs.
const POLISH_MONTHS = [
  ["styczeń", "styczniu", "styczen"],
  ["luty", "lutym", "luty"],
  ["marzec", "marcu", "marzec"],
  ["kwiecień", "kwietniu", "kwiecien"],
  ["maj", "maju", "maj"],
  ["czerwiec", "czerwcu", "czerwiec"],
  ["lipiec", "lipcu", "lipiec"],
  ["sierpień", "sierpniu", "sierpien"],
  ["wrzesień", "wrześniu", "wrzesien"],
  ["październik", "październiku", "pazdziernik"],
  ["listopad", "listopadzie", "listopad"],
  ["grudzień", "grudniu", "grudzien"],
] as const;

export interface ClassicMonth {
  /** "2026-11" */
  yearMonth: string;
  year: number;
  /** 1-12 */
  month: number;
  /** "listopad" */
  name: string;
  /** "listopadzie", for "w listopadzie" */
  locative: string;
  /** "listopad-2026", the URL segment */
  slug: string;
}

export const toClassicMonth = (yearMonth: string): ClassicMonth => {
  const [year, month] = yearMonth.split("-").map(Number);
  const [name, locative, ascii] = POLISH_MONTHS[month - 1];
  return { yearMonth, year, month, name, locative, slug: `${ascii}-${year}` };
};

/** "listopad-2026" -> ClassicMonth, null for anything else. */
export const parseClassicMonthSlug = (slug: string): ClassicMonth | null => {
  const match = /^([a-z]+)-(\d{4})$/.exec(slug);
  if (!match) return null;
  const index = POLISH_MONTHS.findIndex(([, , ascii]) => ascii === match[1]);
  if (index === -1) return null;
  return toClassicMonth(`${match[2]}-${String(index + 1).padStart(2, "0")}`);
};

/** Today in Poland as YYYY-MM-DD. */
export const todayInPoland = (): string =>
  new Date().toLocaleDateString("sv-SE", { timeZone: "Europe/Warsaw" });

const shiftYearMonth = (yearMonth: string, offset: number): string => {
  const [year, month] = yearMonth.split("-").map(Number);
  return new Date(Date.UTC(year, month - 1 + offset, 1))
    .toISOString()
    .slice(0, 7);
};

/**
 * The months that get a page: this one and the next. The scraper looks 31
 * days ahead, so nothing further out has listings yet.
 */
export const getClassicMonths = (today = todayInPoland()): ClassicMonth[] => {
  const current = today.slice(0, 7);
  return [current, shiftYearMonth(current, 1)].map(toClassicMonth);
};

/**
 * Where a month page stands relative to today: "past" months redirect to
 * the hub (their screenings are over, nothing is left to list), "future"
 * ones beyond next month do not exist yet.
 */
export const classicMonthStatus = (
  month: ClassicMonth,
  today = todayInPoland()
): "past" | "live" | "future" => {
  const live = getClassicMonths(today).map((m) => m.yearMonth);
  if (live.includes(month.yearMonth)) return "live";
  return month.yearMonth < live[0] ? "past" : "future";
};

/** Date range of a month page: from today in the current month. */
export const classicMonthRange = (
  month: ClassicMonth,
  today = todayInPoland()
): { dateFrom: string; dateTo: string } => {
  const lastDay = new Date(Date.UTC(month.year, month.month, 0)).getUTCDate();
  const first = `${month.yearMonth}-01`;
  return {
    dateFrom: today > first ? today : first,
    dateTo: `${month.yearMonth}-${String(lastDay).padStart(2, "0")}`,
  };
};

export const fetchClassicScreenings = (range?: {
  dateFrom: string;
  dateTo: string;
}) =>
  fetchScreenings({
    classic: true,
    dateFrom: range?.dateFrom ?? null,
    dateTo: range?.dateTo ?? null,
  });

/** Index decision for a classics page; null when the call failed. */
export const isClassicIndexable = (
  groups: IScreeningGroup[] | null
): boolean | null => (groups === null ? null : groups.length > 0);
